/**
 * Famous space telescopes, probes and the ISS (positions: JPL Horizons via
 * scripts/fetch-spacecraft.mjs; models: NASA 3D Resources, science.nasa.gov,
 * or a schematic model built in code where no free model exists).
 */

/** Local model axis (unit, one component ±1). */
export type Axis = '+x' | '-x' | '+y' | '-y' | '+z' | '-z';

export interface CraftDef {
  id: string;
  name: string;
  kind: 'telescope' | 'probe' | 'station';
  /** Trajectory file (public/data/spacecraft/<track>.bin). */
  track: string;
  /** public/models/spacecraft/<glb>.glb, or a model built in code. */
  model: { glb: string } | { schematic: 'gaia' | 'euclid' | 'clipper' | 'juice' };
  /** Largest dimension (m), the model is scaled to it. */
  sizeM: number;
  /** Which model axis points where (Sun, away from it, or Earth), optionally tipped by tiltDeg (Gaia keeps its shield 45° off the Sun). */
  attitude: { axis: Axis; to: 'sun' | 'antisun' | 'earth'; tiltDeg?: number };
  agency: string;
  /** Launch date (UTC). */
  launch: string;
  /** Mission state, one line. */
  status: string;
  /** Mass at launch (kg). */
  massKg: number;
  text: string[];
  fact: string;
  /** Path / marker colour. */
  color: [number, number, number];
  /** Path shown only this many years either side of now (craft that circle the Sun near Earth for decades). */
  trailYears?: number;
}

