// Fetches orbital and physical data from JPL (run: `npm run data`).
//
//  - Planetary satellite mean elements + physical parameters
//    (ssd.jpl.nasa.gov/sats) → src/data/generated/satellites.json
//  - Dwarf planets and Halley from the Small-Body Database API
//    (ssd-api.jpl.nasa.gov/sbdb.api) → src/data/generated/small-bodies.json
//
// Raw responses are cached in assets-src/data/ so the output is reproducible.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';

const RAW = 'assets-src/data';
const OUT = 'src/data/generated';
mkdirSync(RAW, { recursive: true });
mkdirSync(OUT, { recursive: true });

const UA = { 'User-Agent': 'Mozilla/5.0 (uzay-kesif data script)' };

async function cached(url, file) {
  const path = `${RAW}/${file}`;
  if (existsSync(path) && !process.argv.includes('--refresh')) return readFileSync(path, 'utf8');
  const res = await fetch(url, { headers: UA });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const text = await res.text();
  writeFileSync(path, text);
  return text;
}

const strip = (html) => html.replace(/<[^>]+>/g, ' ').replace(/&[a-z]+;/g, ' ').replace(/\s+/g, ' ').trim();
const num = (cell) => {
  const m = strip(cell).match(/-?\d+(\.\d*)?(e-?\d+)?/i);
  return m ? Number(m[0]) : null;
};

/** Split a page into { planet → [{cells}] } using the panel headings. */
function parsePanels(html, tableClass) {
  const out = {};
  const panels = html.split('<h3 class="panel-title">').slice(1);
  for (const panel of panels) {
    const title = strip(panel.slice(0, panel.indexOf('</h3>')));
    const m = title.match(/Satellites? of (\w+)|^(Moon)$/);
    const planet = m ? (m[1] ?? 'Earth') : title;
    const tStart = panel.indexOf(`<table class="${tableClass}`);
    if (tStart < 0) continue;
    const table = panel.slice(tStart, panel.indexOf('</table>', tStart));
    const headers = [...table.matchAll(/<th[^>]*>([\s\S]*?)<\/th>/g)].map((h) => strip(h[1]));
    const rows = [...table.matchAll(/<tr>([\s\S]*?)<\/tr>/g)]
      .map((r) => [...r[1].matchAll(/<td[^>]*>([\s\S]*?)<\/td>/g)].map((c) => c[1]))
      .filter((r) => r.length > 0);
    const meta = strip(panel.slice(0, tStart));
    (out[planet] ??= []).push({ headers, rows, meta });
  }
  return out;
}

const WANTED = {
  Earth: ['Moon'],
  Mars: ['Phobos', 'Deimos'],
  Jupiter: ['Io', 'Europa', 'Ganymede', 'Callisto', 'Amalthea'],
  Saturn: ['Mimas', 'Enceladus', 'Tethys', 'Dione', 'Rhea', 'Titan', 'Iapetus'],
  Uranus: ['Miranda', 'Ariel', 'Umbriel', 'Titania', 'Oberon'],
  Neptune: ['Triton', 'Nereid'],
  Pluto: ['Charon'],
};

const elemHtml = await cached('https://ssd.jpl.nasa.gov/sats/elem/', 'sats_elem_all.html');
const physHtml = await cached('https://ssd.jpl.nasa.gov/sats/phys_par/sep.html', 'sats_phys.html');
const physPanels = parsePanels(physHtml, 'sat-phys-par');

// The full elements page is one table:
// ID | Planet | Satellite | Code | Ephemeris | Frame | Epoch | a | e | ω | M | i | node | P | Papsis | Pnode | RA | Dec | Tilt | Ref
const tbody = elemHtml.slice(elemHtml.indexOf('<tbody'), elemHtml.indexOf('</tbody>'));
const elemRows = [...tbody.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/g)].map((r) =>
  [...r[1].matchAll(/<td[^>]*>([\s\S]*?)<\/td>/g)].map((c) => c[1]),
);

const satellites = [];
for (const [planet, names] of Object.entries(WANTED)) {
  for (const name of names) {
    const row = elemRows.find((r) => strip(r[1]) === planet && strip(r[2]) === name);
    if (!row) throw new Error(`No elements for ${planet}/${name}`);
    const found = {
      name,
      planet,
      code: Number(strip(row[3])),
      frame: strip(row[5]).toLowerCase(),
      epoch: strip(row[6]),
      aKm: num(row[7]),
      e: num(row[8]),
      omegaDeg: num(row[9]),
      meanAnomalyDeg: num(row[10]),
      iDeg: num(row[11]),
      nodeDeg: num(row[12]),
      periodDays: num(row[13]),
      apsisPeriodYears: num(row[14]),
      nodePeriodYears: num(row[15]),
      laplacePoleRaDeg: num(row[16]),
      laplacePoleDecDeg: num(row[17]),
      laplaceTiltDeg: num(row[18]),
    };
    let phys = null;
    for (const t of physPanels[planet] ?? []) {
      const prow = t.rows.find((r) => strip(r[0]) === name);
      if (prow) phys = { gm: num(prow[1]), meanRadiusKm: num(prow[2]), density: num(prow[3]) };
    }
    satellites.push({ ...found, ...phys });
  }
}

writeFileSync(
  `${OUT}/satellites.json`,
  JSON.stringify(
    {
      _source: 'JPL SSD Planetary Satellite Mean Elements (ssd.jpl.nasa.gov/sats/elem) and Physical Parameters (ssd.jpl.nasa.gov/sats/phys_par). Generated by scripts/fetch-data.mjs.',
      satellites,
    },
    null,
    2,
  ) + '\n',
);
console.log(`satellites: ${satellites.length}`);

// ---- Small bodies --------------------------------------------------------------
const SMALL = [
  { id: 'ceres', sstr: '1' },
  { id: 'pluto', sstr: '134340' },
  { id: 'haumea', sstr: '136108' },
  { id: 'makemake', sstr: '136472' },
  { id: 'eris', sstr: '136199' },
  { id: 'halley', sstr: '1P' },
];
const bodies = [];
for (const b of SMALL) {
  const text = await cached(
    `https://ssd-api.jpl.nasa.gov/sbdb.api?sstr=${encodeURIComponent(b.sstr)}&full-prec=1&phys-par=1`,
    `sbdb_${b.id}.json`,
  );
  const j = JSON.parse(text);
  const el = Object.fromEntries(j.orbit.elements.map((e) => [e.name, Number(e.value)]));
  const phys = Object.fromEntries((j.phys_par ?? []).map((p) => [p.name, p.value]));
  bodies.push({
    id: b.id,
    designation: j.object.fullname,
    kind: j.object.kind,
    epochJd: Number(j.orbit.epoch),
    equinox: j.orbit.equinox,
    aAu: el.a,
    e: el.e,
    iDeg: el.i,
    nodeDeg: el.om,
    periDeg: el.w,
    meanAnomalyDeg: el.ma,
    perihelionJd: el.tp,
    periodDays: el.per,
    meanMotionDegPerDay: el.n,
    diameterKm: phys.diameter ? Number(phys.diameter) : null,
    extentKm: phys.extent ?? null,
    rotationHours: phys.rot_per ? Number(phys.rot_per) : null,
    albedo: phys.albedo ? Number(phys.albedo) : null,
  });
}
writeFileSync(
  `${OUT}/small-bodies.json`,
  JSON.stringify(
    {
      _source: 'JPL Small-Body Database API (ssd-api.jpl.nasa.gov/sbdb.api), heliocentric ecliptic J2000 osculating elements. Generated by scripts/fetch-data.mjs.',
      bodies,
    },
    null,
    2,
  ) + '\n',
);
console.log(`small bodies: ${bodies.length}`);

// ---- NASA Planetary Fact Sheet (info panel numbers) ------------------------------------
const factHtml = await cached('https://nssdc.gsfc.nasa.gov/planetary/factsheet/', 'nasa_factsheet.html');
const sunHtml = await cached('https://nssdc.gsfc.nasa.gov/planetary/factsheet/sunfact.html', 'nasa_sunfact.html');
const factRows = [...factHtml.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/gi)].map((r) =>
  [...r[1].matchAll(/<t[dh][^>]*>([\s\S]*?)<\/t[dh]>/gi)].map((c) => strip(c[1])),
);
const header = factRows[0].map((h) => h.toLowerCase());
const ROW_KEYS = {
  'Mass': 'mass1e24kg',
  'Diameter': 'diameterKm',
  'Density': 'density',
  'Gravity': 'gravity',
  'Escape Velocity': 'escapeVelocity',
  'Rotation Period': 'rotationHours',
  'Length of Day': 'dayHours',
  'Distance from Sun': 'distance1e6km',
  'Perihelion': 'perihelion1e6km',
  'Aphelion': 'aphelion1e6km',
  'Orbital Period': 'orbitalPeriodDays',
  'Orbital Velocity': 'orbitalVelocity',
  'Orbital Inclination': 'inclinationDeg',
  'Orbital Eccentricity': 'eccentricity',
  'Obliquity to Orbit': 'obliquityDeg',
  'Mean Temperature': 'meanTempC',
  'Surface Pressure': 'surfacePressureBar',
  'Number of Moons': 'moons',
  'Ring System?': 'rings',
  'Global Magnetic Field?': 'magneticField',
};
const facts = {};
for (const row of factRows.slice(1)) {
  const key = Object.entries(ROW_KEYS).find(([label]) => row[0]?.startsWith(label))?.[1];
  if (!key) continue;
  for (let i = 1; i < row.length; i++) {
    const body = header[i];
    if (!body) continue;
    const raw = row[i].replace(/,/g, '');
    let value;
    if (/^(yes|no|unknown)/i.test(raw)) value = raw.toLowerCase().startsWith('yes') ? true : raw.toLowerCase().startsWith('no') ? false : null;
    else if (/unknown/i.test(raw)) value = null;
    else value = Number(raw.replace(/\*/g, ''));
    (facts[body] ??= {})[key] = value;
  }
}
const sunText = strip(sunHtml);
const sunNum = (re) => {
  const m = sunText.match(re);
  return m ? Number(m[1].replace(/,/g, '')) : null;
};
facts.sun = {
  mass1e24kg: sunNum(/Mass \(10 24 kg\) ([\d,.]+)/),
  radiusKm: sunNum(/Volumetric mean radius \(km\) ([\d,.]+)/),
  density: sunNum(/Mean density \(kg\/m 3 \) ([\d,.]+)/),
  gravity: sunNum(/Surface gravity \(eq\.\) \(m\/s 2 \) ([\d,.]+)/),
  escapeVelocity: sunNum(/Escape velocity \(km\/s\) ([\d,.]+)/),
  rotationHours: sunNum(/Sidereal rotation period \(hrs\)\* ([\d,.]+)/),
  effectiveTempK: sunNum(/Effective temperature: ([\d,.]+) K/),
  luminosity1e24W: sunNum(/Luminosity \(10 24 J\/s\) ([\d,.]+)/),
  centralTempK: (() => {
    const m = sunText.match(/Central temperature: ([\d.]+) x 10 (\d+) K/);
    return m ? Number(m[1]) * 10 ** Number(m[2]) : null;
  })(),
};
writeFileSync(
  `${OUT}/facts.json`,
  JSON.stringify(
    {
      _source: 'NASA GSFC Planetary Fact Sheet (nssdc.gsfc.nasa.gov/planetary/factsheet) and Sun Fact Sheet. Values as published; Moon distances are from Earth. Generated by scripts/fetch-data.mjs.',
      fetched: new Date().toISOString().slice(0, 10),
      bodies: facts,
    },
    null,
    2,
  ) + '\n',
);
console.log(`facts: ${Object.keys(facts).join(', ')}`);
